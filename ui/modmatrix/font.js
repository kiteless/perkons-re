function glyph(ch) {
  const g = FONT[ch] || FONT[ch.toUpperCase()];
  return g || FONT["?"];
}

/* draw `text` at (x, y) top-left, `s` screen pixels per font pixel */
function drawText(ctx, text, x, y, s, color) {
  ctx.fillStyle = color;
  for (let i = 0; i < text.length; i++) {
    const g = glyph(text[i]);
    for (let r = 0; r < 8; r++) {
      let bits = g[r];
      if (!bits) continue;
      for (let c = 0; c < 8; c++) {
        if (bits & (0x80 >> c)) ctx.fillRect(x + (i * 8 + c) * s, y + r * s, s, s);
      }
    }
  }
}

/* word-wrap to `cols` characters per line (long words are split) */
function wrap(text, cols) {
  const lines = [];
  for (const para of String(text).split("\n")) {
    let line = "";
    for (let word of para.split(" ")) {
      while (word.length > cols) {
        if (line) { lines.push(line); line = ""; }
        lines.push(word.slice(0, cols)); word = word.slice(cols);
      }
      if (!line) line = word;
      else if (line.length + 1 + word.length <= cols) line += " " + word;
      else { lines.push(line); line = word; }
    }
    lines.push(line);
  }
  return lines;
}
