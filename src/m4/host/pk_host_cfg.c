/* M4 host: config-page toggles (linked when a mod registers one): each toggle's key flips
 * its variable, marks the config for saving and shows on its LED. Chained hooks on the
 * config page's event and render words, so mods can take the page over before them. */
#include <stdint.h>
#include "pk_host.h"

#define LED_ON          0x80

typedef struct {
    uint8_t key;
    uint8_t *var;
} pk_toggle_t;

extern const pk_toggle_t pk_toggles[];      /* generated by m4host.py */
extern const int pk_n_toggles;

int PK_NEXT(pk4_cfg_event)(const uint8_t *evt);
void PK_NEXT(pk4_cfg_render)(void *a, void *b, void *c, void *d);

int pk4_cfg_event(const uint8_t *evt)
{
    if (evt[1] == CONST_cfg_key_event) {
        for (int i = 0; i < pk_n_toggles; i++) {
            if (evt[0] == pk_toggles[i].key) {
                *pk_toggles[i].var ^= 1;
                FW_CFG_DIRTY = 1;       /* saved (mods.json) on page exit */
                return 1;
            }
        }
    }
    return PK_NEXT(pk4_cfg_event)(evt);
}

void pk4_cfg_render(void *a, void *b, void *c, void *d)
{
    PK_NEXT(pk4_cfg_render)(a, b, c, d);
    for (int i = 0; i < pk_n_toggles; i++)
        fw_set_led(pk_toggles[i].key, *pk_toggles[i].var ? LED_ON : 0);
}
