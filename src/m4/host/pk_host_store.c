/* M4 host: mods' per-pattern and per-kit data in sidecar files (host.store in m4host.py).
 *
 * BANKS/NN/PP.PAX and BANKS/NN/KITS/PP.KIX hold one record per mod beside the stock
 * PP.PAT / PP.KIT, which stay stock: "PKX1", then {char tag[4], u32 length, data} per
 * record. Unknown tags are skipped, so a file stays readable whatever mods a build has.
 * Saving a pattern or kit writes its file (records from each mod's save function);
 * clearing a pattern deletes it; a bank load lists the bank's folders once, reads the files
 * there and hands every mod its record for all 64 of each (length 0: none, e.g. no file). */
#include <stdint.h>
#include "pk_host.h"

#define MAGIC           0x31584b50u     /* "PKX1" */
#define REC_MAX         ((uint32_t)CONST_json_buf_size)
#define NIDX            64

typedef struct {
    char tag[4];
    uint32_t (*save)(int bank, int idx, uint8_t *buf, uint32_t max);
    void (*load)(int bank, int idx, const uint8_t *rec, uint32_t len);
} pk_store_t;

/* generated by m4host.py (gen/pk_host_gen.c) */
extern const pk_store_t pk_store_pattern[], pk_store_kit[];
extern const int pk_n_store_pattern, pk_n_store_kit;

/* the firmware's JSON file object and 4 KB text buffer: free between its file operations */
#define FIL             ((void *)(uintptr_t)SYM_json_file)
#define BUF             ((uint8_t *)(uintptr_t)SYM_json_buf)

static void path(char *name, int kit, int bank, int idx)
{
    fw_snprintf(name, 32, kit ? "BANKS/%02d/KITS/%02d.KIX" : "BANKS/%02d/%02d.PAX", bank, idx);
}

static void write_file(const pk_store_t *t, int n, int kit, int bank, int idx)
{
    char name[32];
    path(name, kit, bank, idx);
    int open = 0;
    unsigned put;
    for (int i = 0; i < n; i++) {
        uint32_t len = t[i].save(bank, idx, BUF, REC_MAX);
        if (!len)
            continue;
        if (!open) {
            if (fw_f_open(FIL, name, FW_FA_WRITE_NEW) != 0)
                return;
            uint32_t magic = MAGIC;
            fw_f_write(FIL, &magic, 4, &put);
            open = 1;
        }
        fw_f_write(FIL, t[i].tag, 4, &put);
        fw_f_write(FIL, &len, 4, &put);
        fw_f_write(FIL, BUF, len, &put);
    }
    if (open)
        fw_f_close(FIL);
    else
        fw_f_unlink(name);              /* no mod has anything: no file */
}

/* which of a folder's files are NN.<ext> (NN < 64): bit NN of mask[2]. One listing per
 * bank load instead of an open per index, most of which find nothing (the JSON buffer
 * holds the DIR and FILINFO meanwhile). */
static int digit(char c)
{
    return c >= '0' && c <= '9';
}

_Static_assert(FW_DIR_MAX + FW_FNO_SIZE <= CONST_json_buf_size, "DIR and FILINFO fit the JSON buffer");

static void listing(const char *dir, const char *ext, uint32_t mask[2])
{
    uint8_t *d = BUF, *fno = BUF + FW_DIR_MAX;
    mask[0] = mask[1] = 0;
    if (fw_f_opendir(d, dir) != 0)
        return;
    while (fw_f_readdir(d, fno) == 0 && fno[FW_FNO_NAME]) {
        const char *s = (const char *)fno + FW_FNO_NAME;
        int ok = digit(s[0]) && digit(s[1]) && s[2] == '.' && !s[6];
        for (int i = 0; ok && i < 3; i++)
            ok = (s[3 + i] & ~0x20) == ext[i];          /* any case */
        int idx = ok ? (s[0] - '0') * 10 + (s[1] - '0') : NIDX;
        if (idx < NIDX)
            mask[idx >> 5] |= 1u << (idx & 31);
    }
    fw_f_closedir(d);
}

static void read_file(const pk_store_t *t, int n, int kit, int bank, int idx, int there)
{
    char name[32];
    path(name, kit, bank, idx);
    uint32_t seen = 0;
    unsigned got;
    if (there && fw_f_open(FIL, name, FW_FA_READ) == 0) {
        uint32_t head[2];
        if (fw_f_read(FIL, head, 4, &got) == 0 && got == 4 && head[0] == MAGIC) {
            while (fw_f_read(FIL, head, 8, &got) == 0 && got == 8) {
                uint32_t len = head[1];
                int which = -1;
                for (int i = 0; i < n; i++)
                    if (*(const uint32_t *)t[i].tag == head[0])
                        which = i;
                if (len <= REC_MAX) {
                    if (fw_f_read(FIL, BUF, len, &got) != 0 || got != len)
                        break;
                    if (which >= 0 && !(seen >> which & 1)) {
                        seen |= 1u << which;
                        t[which].load(bank, idx, BUF, len);
                    }
                } else {                /* too long for anyone here: skip it */
                    while (len) {
                        uint32_t k = len < REC_MAX ? len : REC_MAX;
                        if (fw_f_read(FIL, BUF, k, &got) != 0 || got != k)
                            break;
                        len -= k;
                    }
                }
            }
        }
        fw_f_close(FIL);
    }
    for (int i = 0; i < n; i++)
        if (!(seen >> i & 1))
            t[i].load(bank, idx, 0, 0);
}

/* chain links (order first: they run the rest of the chain, then do their part) */
int PK_NEXT(pk4_store_pat_save)(uint8_t *hdr, int bank, int idx);
void PK_NEXT(pk4_store_pat_clear)(int bank, int idx);
void PK_NEXT(pk4_store_bank_load)(int bank);
int PK_NEXT(pk4_store_kit_save)(int bank, int kit);

int pk4_store_pat_save(uint8_t *hdr, int bank, int idx)
{
    int r = PK_NEXT(pk4_store_pat_save)(hdr, bank, idx);
    if (idx >= 0 && idx < NIDX)
        write_file(pk_store_pattern, pk_n_store_pattern, 0, bank, idx);
    return r;
}

void pk4_store_pat_clear(int bank, int idx)
{
    PK_NEXT(pk4_store_pat_clear)(bank, idx);
    if (idx < 0 || idx >= NIDX)
        return;
    char name[32];
    path(name, 0, bank, idx);
    fw_f_unlink(name);
    for (int i = 0; i < pk_n_store_pattern; i++)
        pk_store_pattern[i].load(bank, idx, 0, 0);
}

void pk4_store_bank_load(int bank)
{
    PK_NEXT(pk4_store_bank_load)(bank);
    char dir[24];
    uint32_t pat[2] = {0, 0}, kit[2] = {0, 0};
    if (pk_n_store_pattern) {
        fw_snprintf(dir, sizeof dir, "BANKS/%02d", bank);
        listing(dir, "PAX", pat);
    }
    if (pk_n_store_kit) {
        fw_snprintf(dir, sizeof dir, "BANKS/%02d/KITS", bank);
        listing(dir, "KIX", kit);
    }
    for (int idx = 0; idx < NIDX; idx++) {
        if (pk_n_store_pattern)
            read_file(pk_store_pattern, pk_n_store_pattern, 0, bank, idx, pat[idx >> 5] >> (idx & 31) & 1);
        if (pk_n_store_kit)
            read_file(pk_store_kit, pk_n_store_kit, 1, bank, idx, kit[idx >> 5] >> (idx & 31) & 1);
    }
}

/* kit_save's result (the kit file saved) makes the kit page flash the step: pass it on */
int pk4_store_kit_save(int bank, int kit)
{
    int r = PK_NEXT(pk4_store_kit_save)(bank, kit);
    if (kit >= 0 && kit < NIDX)
        write_file(pk_store_kit, pk_n_store_kit, 1, bank, kit);
    return r;
}

void pk_store_save_pattern(int bank, int idx)
{
    if (idx >= 0 && idx < NIDX)
        write_file(pk_store_pattern, pk_n_store_pattern, 0, bank, idx);
}

void pk_store_save_kit(int bank, int kit)
{
    if (kit >= 0 && kit < NIDX)
        write_file(pk_store_kit, pk_n_store_kit, 1, bank, kit);
}
