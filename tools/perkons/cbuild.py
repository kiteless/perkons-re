"""Compile C patch code for a code cave with arm-none-eabi-gcc.

Generated headers (in <build>/gen/):
  fw_syms.h      #define SYM_<name> <addr> for every function/global in symbols/*.json
  + whatever the patch passes as extra_headers (e.g. tables generated from the emulator)

The firmware interface headers in include/<core>/ (fw_m7.h, fw_m4.h) are always on the
include path.

The cave has no startup code of its own, so the link fails if anything lands in
.data or .bss. Patch state lives at fixed RAM addresses chosen in the C code.
"""
import os
import re
import shutil
import subprocess


ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FW_INCLUDE = {core: os.path.join(ROOT, 'include', core) for core in ('m4', 'm7')}
TOOLCHAIN = os.environ.get('ARM_GCC_PREFIX', 'arm-none-eabi-')
CPU_FLAGS = {
    'm7': ['-mcpu=cortex-m7', '-mfpu=fpv5-d16'],
    'm4': ['-mcpu=cortex-m4', '-mfpu=fpv4-sp-d16'],
}
CFLAGS = ['-mthumb', '-mfloat-abi=hard', '-Os', '-std=c11', '-ffreestanding', '-fno-builtin', '-nostdlib',
          '-ffunction-sections', '-fdata-sections', '-fno-common', '-Wall', '-Wextra', '-Werror']

LINKER_SCRIPT = """
MEMORY {{ CAVE (rx) : ORIGIN = 0x{origin:08x}, LENGTH = 0x{length:x} }}
ENTRY({entry})
SECTIONS {{
  .text : {{ KEEP(*(.text.pk_*)) *(.text*) *(.rodata*) }} > CAVE
  .data : {{ *(.data*) }} > CAVE
  .bss  : {{ *(.bss*) *(COMMON) }} > CAVE
  /DISCARD/ : {{ *(.ARM.*) *(.comment) *(.note*) }}
}}
ASSERT(SIZEOF(.data) == 0, "patch code must not use initialized globals (no startup code in the cave)")
ASSERT(SIZEOF(.bss) == 0, "patch code must not use zero-init globals; use fixed RAM via pointers")
"""


class BuildError(Exception):
    pass


def tool(name):
    path = shutil.which(TOOLCHAIN + name)
    if not path:
        raise BuildError(f'{TOOLCHAIN}{name} not found (brew install arm-none-eabi-gcc arm-none-eabi-binutils)')
    return path


def _ident(name):
    return re.sub(r'[^A-Za-z0-9_]', '_', name)


def gen_syms_header(sym):
    """SYM_<fn|global>, OFF_<struct>_<field>, CONST_<name>, SITE_<name> from a symbols file."""
    lines = ['/* generated by tools/perkons/cbuild.py from the symbols JSON -- do not edit */', '#pragma once']
    for section in ('functions', 'globals'):
        for k, v in sym.raw.get(section, {}).items():
            if k.startswith('_') or not isinstance(v, str) or not v.startswith('0x'):
                continue
            lines.append(f'#define SYM_{_ident(k)} {v}u')
    for prefix, table in (('OFF', sym.off), ('CONST', sym.const)):
        for k, v in table.items():
            lines.append(f'#define {prefix}_{_ident(k)} 0x{v:x}u')
    for k in sym.sites:
        lines.append(f'#define SITE_{_ident(k)} 0x{sym.site(k)["addr"]:08x}u')
    if 'min_stack' in sym.raw.get('heap', {}):
        lines.append(f'#define SYM_heap_min_stack {sym.raw["heap"]["min_stack"]}u')
    return '\n'.join(lines) + '\n'


def build(core, src_files, include_dirs, build_dir, origin, entry, sym, extra_headers=None, defines=None,
          max_len=0x10000):
    """Compile+link for `core` ('m4'/'m7') at `origin`. Writes gen/fw_syms.h plus any
    extra_headers {name: text}. Returns (blob, {symbol: addr})."""
    gen = os.path.join(build_dir, 'gen')
    os.makedirs(gen, exist_ok=True)
    headers = {'fw_syms.h': gen_syms_header(sym), **(extra_headers or {})}
    for name, text in headers.items():
        with open(os.path.join(gen, name), 'w') as f:
            f.write(text)
    ld = os.path.join(build_dir, 'cave.ld')
    with open(ld, 'w') as f:
        f.write(LINKER_SCRIPT.format(origin=origin, length=max_len, entry=entry))
    elf = os.path.join(build_dir, 'cave.elf')
    cmd = [tool('gcc'), *CPU_FLAGS[core], *CFLAGS, f'-I{gen}', *[f'-I{d}' for d in include_dirs],
           f'-I{FW_INCLUDE[core]}',
           *[f'-D{k}={v}' for k, v in (defines or {}).items()],
           '-Wl,--gc-sections', f'-Wl,-T,{ld}', f'-Wl,-Map,{elf}.map', '-o', elf, *src_files]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        raise BuildError('compile failed:\n' + r.stderr)
    binf = os.path.join(build_dir, 'cave.bin')
    subprocess.run([tool('objcopy'), '-O', 'binary', '-j', '.text', elf, binf], check=True)
    out = subprocess.run([tool('nm'), elf], capture_output=True, text=True, check=True).stdout
    syms = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in 'Tt':
            syms[parts[2]] = int(parts[0], 16)
    with open(os.path.join(build_dir, 'cave.lst'), 'w') as f:
        f.write(subprocess.run([tool('objdump'), '-d', elf], capture_output=True, text=True).stdout)
    with open(binf, 'rb') as f:
        return f.read(), syms
