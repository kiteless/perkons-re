"""Hook chains for the core hosts (m4host, m7host).

Several mods may hook the same firmware site: a `bl` (call), a tail `b.w` (branch) or a
literal holding a function pointer (word). A host collects every registration, then:

* sorts each site's hooks (order, then symbol name) into a chain, and gives each hook
  its next one: the next hook, or the stock function. A hook used at several sites must
  have the same next hook at each (else HostError);
* generates, in assembly, a guard per chain head (until the host has booted, i.e. its
  magic word is set, go straight to the stock function), a `pk_next_<hook>` trampoline
  per hook (PK_NEXT(hook) in C), and event links (call each subscriber, then go on);
* after the link, points each site at its guard.

A word that is not a code pointer is a data pointer: replaced outright, by one mod only.
"""


class HostError(Exception):
    pass


def collect(sym, hooks, flash, event_links=()):
    """hooks: [(kind, site, symbol, why, order)]; event_links: the same, for events.
    Returns ({addr: chain}, {addr: (site, symbol, why)} for data words, {hook: next})."""
    chains, data = {}, {}
    for kind, site, symbol, why, order in list(hooks) + list(event_links):
        s = sym.site(site)
        addr = s['addr']
        if kind == 'word':
            w = s['word']
            if not (w & 1 and flash[0] <= w < flash[1]):                  # a data pointer
                if addr in data and data[addr][1] != symbol:
                    raise HostError(f'{site}: data word wanted by {symbol} and {data[addr][1]}')
                data[addr] = (site, symbol, why)
                continue
            stock = w & ~1
        else:
            stock = sym.fn[s['call']]
        c = chains.setdefault(addr, {'kind': kind, 'stock': stock, 'site': site, 'links': []})
        if (c['kind'], c['stock']) != (kind, stock):
            raise HostError(f'{site} and {c["site"]} are the same site but different hooks')
        if symbol not in [l[1] for l in c['links']]:
            c['links'].append((order, symbol, why))
    nxt, guards = {}, {}
    for addr in sorted(chains):
        c = chains[addr]
        c['links'].sort()
        names = [l[1] for l in c['links']]
        for i, n in enumerate(names):
            v = names[i + 1] if i + 1 < len(names) else c['stock']
            if nxt.setdefault(n, v) != v:
                raise HostError(f'{n} continues to {nxt[n]} at one site and to {v} at {c["site"]}: '
                                'a hook must have the same next hook at every site')
        c['guard'] = guards.setdefault((c['stock'], names[0]), f'pk_guard_{len(guards)}')
    return chains, data, nxt


def event_links(sym, events):
    """Chain links for subscribed events: the sites named event.<name>.* in the symbols."""
    out = []
    for ev in sorted(events):
        sites = sorted(k for k in sym.sites if k.startswith(f'event.{ev}.'))
        if not sites:
            raise HostError(f'event {ev}: no event.{ev}.* sites in the symbols')
        for site in sites:
            s = sym.site(site)
            kind = 'word' if 'word' in s else 'branch' if s.get('branch') else 'call'
            out.append((kind, site, f'pk_ev_{ev}', f'event {ev}', -1000))
    return out


def gen_source(chains, nxt, events, magic_symbol, magic):
    """C source (top-level assembly): guards, PK_NEXT trampolines, event links."""
    def jump(target):
        if isinstance(target, int):               # a firmware function
            return f'ldr ip, 9f\n bx ip\n .align 2\n9: .word 0x{target | 1:08x}\n'
        return f'b.w {target}\n'

    def fn(name, body):
        return (f'.section .text.{name},"ax",%progbits\n.global {name}\n.type {name}, %function\n'
                f'.thumb_func\n{name}:\n{body}')
    out, seen = [], set()
    for addr in sorted(chains):
        c = chains[addr]
        if c['guard'] in seen:
            continue
        seen.add(c['guard'])
        out.append(fn(c['guard'],
                      ' push {r0}\n ldr r0, 7f\n ldr r0, [r0]\n ldr ip, 8f\n cmp r0, ip\n pop {r0}\n'
                      f' bne 6f\n b.w {c["links"][0][1]}\n6: ' + jump(c['stock']) +
                      f' .align 2\n7: .word {magic_symbol}\n8: .word 0x{magic:08x}\n'))
    for name in sorted(nxt):
        out.append(fn(f'pk_next_{name}', jump(nxt[name])))
    for ev in sorted(events):
        calls = ''.join(f' bl {f}\n' for f in sorted(events[ev]))
        out.append(fn(f'pk_ev_{ev}', ' push {r0, r1, r2, r3, ip, lr}\n vpush {s0-s15}\n' + calls +
                      ' vpop {s0-s15}\n pop {r0, r1, r2, r3, ip, lr}\n' + jump(f'pk_next_pk_ev_{ev}')))
    body = '.syntax unified\n.thumb\n' + ''.join(out)
    return ('/* generated by tools/perkons/hooks.py -- do not edit: hook chains */\n'
            + f'extern unsigned {magic_symbol};\n'
            + '__asm__(' + ''.join('"' + line.replace('"', '\\"') + '\\n"\n' for line in body.split('\n') if line)
            + ');\n')


def apply(p, core, chains, data, syms):
    """Point every chained site at its guard; replace data words."""
    for addr in sorted(chains):
        c = chains[addr]
        why = ' + '.join(l[2] for l in c['links'])
        target = syms[c['guard']] | 1
        if c['kind'] == 'word':
            p.replace_word(core, c['site'], target, why)
        else:
            getattr(p, f'redirect_{c["kind"]}')(core, c['site'], target, why)
    for addr in sorted(data):
        site, symbol, why = data[addr]
        p.replace_word(core, site, syms[symbol], why)


def unregistered(err):
    """Hooks a link failed on because they call PK_NEXT without being registered."""
    import re
    return sorted(set(re.findall(r"undefined reference to `pk_next_(\w+)'", str(err))))
