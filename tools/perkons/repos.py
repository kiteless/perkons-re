"""Mod repos: where the Mod Matrix finds mods, on GitHub.

A mod repo is a GitHub repo of mods (each a directory with its mod.json, as perkons.mods
describes), with two files at its root:

    perkons-repo.json    written by its author: {"repo": "owner/name", "description": "..."}
    perkons-mods.json    generated by tools/manifest.py: the repo, its description and every
                         option of every mod in it, with what each takes of the RAM areas
                         (measured by building it), per firmware version

The repos the Mod Matrix offers are listed in repos.json in kiteless/perkons-re-mods
(CONFIG_URL; PERKONS_REPOS_URL overrides it):

    {"repos": [{"repo": "kiteless/perkons-re-mods", "default": true},
               {"repo": "someone/their-mods", "ref": "main"}]}

A repo may carry a "note", shown under it in full (the description is cut to one line).

The list and each ticked repo's manifest are fetched when the Mod Matrix starts; a mod's
files only when a build needs them (download()), from the commit the repo is at then, kept
in .cache/repos/<owner>/<name>/<commit>/. Fetched files are kept too (.cache/remote/), so the
last list and manifests are used when GitHub can't be reached.

Option ids are namespaced, "owner/name:id", so two repos can use the same id; a mod's
requires and conflicts may name ids in its own repo plainly or another repo's in full.
"""
import json
import os
import re
import threading
import urllib.request

from .mods import ROOT

HOME = 'kiteless/perkons-re-mods'      # the main mod repo: listed first, and holds the repo list
CONFIG_URL = f'https://raw.githubusercontent.com/{HOME}/main/repos.json'
RAW = 'https://raw.githubusercontent.com/{repo}/{ref}/{path}'
API = 'https://api.github.com/repos/{repo}/{what}'
CACHE = os.path.join(ROOT, '.cache')
REPO_FILE, MANIFEST = 'perkons-repo.json', 'perkons-mods.json'
MANIFEST_FORMAT = 1
TIMEOUT = 15
REPO_RE = re.compile(r'^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$')


class RepoError(Exception):
    pass


def _urlopen(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'perkons-mod-matrix'})
    with urllib.request.urlopen(req, timeout=TIMEOUT) as r:
        return r.read()


FETCH = _urlopen        # url -> bytes; tests replace it


def _cached_fetch(url):
    """FETCH(url), kept on disk; the kept copy if GitHub can't be reached."""
    path = os.path.join(CACHE, 'remote', re.sub(r'[^A-Za-z0-9_.-]', '_', url.split('://', 1)[-1]))
    try:
        data = FETCH(url)
    except Exception as e:
        if os.path.exists(path):
            with open(path, 'rb') as f:
                return f.read()
        raise RepoError(f'can\'t fetch {url}: {e}') from None
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path + '.tmp', 'wb') as f:
        f.write(data)
    os.replace(path + '.tmp', path)
    return data


def _json(data, what):
    try:
        return json.loads(data)
    except ValueError as e:
        raise RepoError(f'{what}: not valid JSON ({e})') from None


def check_repo(name):
    if not isinstance(name, str) or not REPO_RE.match(name):
        raise RepoError(f'not a GitHub repo name (owner/name): {name!r}')
    return name


def config(url=None):
    """The repos to offer: [{repo, ref, default, note}]."""
    url = url or os.environ.get('PERKONS_REPOS_URL') or CONFIG_URL
    spec = _json(_cached_fetch(url), url)
    out, seen = [], set()
    for r in spec.get('repos', []):
        name = check_repo(r.get('repo'))
        if name.lower() in seen:
            continue
        seen.add(name.lower())
        out.append({'repo': name, 'ref': r.get('ref', 'main'), 'default': bool(r.get('default')),
                    'note': str(r.get('note', ''))})
    return out


def manifest(repo, ref='main'):
    """A repo's perkons-mods.json, checked."""
    m = _json(_cached_fetch(RAW.format(repo=repo, ref=ref, path=MANIFEST)), f'{repo} {MANIFEST}')
    if m.get('format') != MANIFEST_FORMAT:
        raise RepoError(f'{repo}: {MANIFEST} format {m.get("format")!r}, this Mod Matrix reads {MANIFEST_FORMAT}')
    if str(m.get('repo', '')).lower() != repo.lower():
        raise RepoError(f'{repo}: its {MANIFEST} is for {m.get("repo")!r}')
    return m


def qualify(repo, ref_id):
    """An id as a mod in `repo` names it -> its full id."""
    return ref_id if ':' in ref_id else f'{repo}:{ref_id}'


def options(m, ref='main', local=None):
    """A manifest's options, as catalog options (full ids). local: the repo's directory, if
    it's on disk (a developer's clone): its mods are built from there, not downloaded."""
    repo = m['repo']
    out = []
    for o in m.get('mods', []):
        readme = o.get('readme')
        out.append({'id': qualify(repo, o['id']), 'title': o['title'], 'summary': o['summary'],
                    'description': o.get('description', ''),
                    'readme': f'https://github.com/{repo}/blob/{ref}/{readme}' if readme else None,
                    'patches': list(o['patches']), 'code': o['code'],
                    'conflicts': [qualify(repo, c) for c in o.get('conflicts', [])],
                    'requires': [qualify(repo, r) for r in o.get('requires', [])],
                    'kind': o.get('kind', 'mod'), 'dir': o['dir'], 'mod': o['dir'],
                    'repo': repo, 'ref': ref, 'author': o.get('author', repo.split('/')[0]), 'local': local,
                    'target': o.get('target'),
                    'memory': o.get('memory', {})})
    return out


# -- downloads: a build's mods, only those ------------------------------------------------

_lock = threading.Lock()


def commit(repo, ref):
    c = _json(FETCH(API.format(repo=repo, what=f'commits/{ref}')), f'{repo} commit')
    return c['sha']


def download(repo, ref, dirs):
    """The repo's directories `dirs` (and its root files) at the commit `ref` is at now, in
    the cache. Returns the repo's directory there (its mods are <it>/<dir>)."""
    with _lock:
        sha = commit(repo, ref)
        root = os.path.join(CACHE, 'repos', *repo.split('/'), sha)
        want = [d for d in dirs if not os.path.exists(os.path.join(root, d, '.complete'))]
        if not want and os.path.exists(os.path.join(root, '.complete')):
            return root
        tree = _json(FETCH(API.format(repo=repo, what=f'git/trees/{sha}?recursive=1')), f'{repo} tree')
        if tree.get('truncated'):
            raise RepoError(f'{repo}: too many files to list')
        blobs = [t['path'] for t in tree['tree'] if t['type'] == 'blob']
        for d in want + ['']:
            files = [b for b in blobs if b.startswith(d + '/')] if d else [b for b in blobs if '/' not in b]
            if d and not files:
                raise RepoError(f'{repo}: no directory {d!r}')
            for path in files:
                dest = os.path.join(root, *path.split('/'))
                if not os.path.normpath(dest).startswith(os.path.normpath(root) + os.sep):
                    raise RepoError(f'{repo}: bad path {path!r}')
                os.makedirs(os.path.dirname(dest), exist_ok=True)
                data = FETCH(RAW.format(repo=repo, ref=sha, path=path))
                with open(dest + '.tmp', 'wb') as f:
                    f.write(data)
                os.replace(dest + '.tmp', dest)
            open(os.path.join(root, d, '.complete'), 'w').close()
        return root


# -- which repo a directory on disk belongs to -----------------------------------------------

def repo_root(path):
    """(the mod repo containing `path`, its owner/name), from its perkons-repo.json; or
    (None, None)."""
    d = os.path.abspath(path)
    while True:
        f = os.path.join(d, REPO_FILE)
        if os.path.exists(f):
            with open(f) as fh:
                return d, check_repo(json.load(fh)['repo'])
        up = os.path.dirname(d)
        if up == d:
            return None, None
        d = up
